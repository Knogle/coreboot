static bool overlap(const void *a, size_t a_bytes, const void *b, size_t b_bytes)
{
	return (uintptr_t)a < (uintptr_t)b + b_bytes &&
		(uintptr_t)b < (uintptr_t)a + a_bytes;
}

size_t matisse_build_nbio_base_plan(enum matisse_nbio_base_program program,
		struct matisse_dxio_configured_step *output, size_t capacity)
{
	const struct base_step *first = am4_defaults, *second = NULL;
	size_t first_count = sizeof(am4_defaults) / sizeof(am4_defaults[0]);
	size_t second_count = 0;

	switch (program) {
	case MATISSE_NBIO_BASE_AM4_DEFAULTS:
		break;
	case MATISSE_NBIO_BASE_COMMON_DEFAULTS:
		first = common_defaults;
		first_count = sizeof(common_defaults) / sizeof(common_defaults[0]);
		break;
	case MATISSE_NBIO_BASE_INITIAL_AM4_DEFAULTS:
		second = common_defaults;
		second_count = sizeof(common_defaults) / sizeof(common_defaults[0]);
		break;
	default:
		return 0;
	}
	size_t count = first_count + second_count;
	size_t bytes = count * sizeof(*output);

	if (!output || capacity < count || (uintptr_t)output > UINTPTR_MAX - bytes ||
	    overlap(output, bytes, am4_defaults, sizeof(am4_defaults)) ||
	    overlap(output, bytes, common_defaults, sizeof(common_defaults)))
		return 0;
	for (size_t i = 0; i < count; i++) {
		const struct base_step *step = i < first_count ?
			&first[i] : &second[i - first_count];

		output[i] = (struct matisse_dxio_configured_step) {
			.kind = step->write ? MATISSE_DXIO_CONFIGURED_WRITE :
				MATISSE_DXIO_CONFIGURED_RMW,
			.address = step->address, .and_mask = step->and_mask, .value = step->value,
		};
	}
	return count;
}
